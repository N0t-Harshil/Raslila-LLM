"""Parameter-Shift Exact Gradients - for quantum parameters.

Implements exact gradient computation using parameter-shift rule:
∂f(θ)/∂θ = [f(θ + π/2) - f(θ - π/2)] / 2

For Hamiltonian parameters generated by Pauli operators, this gives
exact gradients without finite-difference noise.
"""
import numpy as np
from typing import Callable, List, Dict, Tuple
from dataclasses import dataclass
from .hamiltonian import RaslilaHamiltonian
from .evolution import evolve, state_probs, nll_loss, T_FIXED, uniform_initial_state


@dataclass
class GradientResult:
    """Container for gradient computation results."""
    gradients: np.ndarray
    method: str  # 'parameter_shift', 'finite_diff', 'ad'
    evaluations: int  # number of circuit evaluations
    metadata: Dict


class ParameterShiftGradients:
    """
    Exact gradients for quantum circuit parameters using parameter-shift rule.

    For a parameter θ appearing in a gate exp(-i θ P/2) where P is Pauli:
    ∂⟨O⟩/∂θ = (⟨O⟩_{θ+π/2} - ⟨O⟩_{θ-π/2}) / 2

    In our case, parameters appear in Hamiltonian terms like α X_a X_b.
    Since H = α X_a X_b + ..., the evolution is exp(-i α X_a X_b T).
    The parameter-shift rule applies with shift π/(2T).
    """

    SHIFT = np.pi / 2  # Standard shift for Pauli generators

    def __init__(self, hamiltonian: RaslilaHamiltonian,
                 init_state: np.ndarray,
                 target_bits: Tuple[int, ...],
                 readout_qubits: Tuple[int, ...]):
        self.ham = hamiltonian
        self.init_state = init_state
        self.target_bits = target_bits
        self.readout_qubits = readout_qubits
        self.n_qubits = getattr(hamiltonian, 'n', getattr(hamiltonian, 'n_qubits', None))

    def _loss(self, ham: RaslilaHamiltonian) -> float:
        """Compute NLL loss for given Hamiltonian."""
        H = ham.construct_dense()
        final = evolve(H, self.init_state, T_FIXED)
        probs = state_probs(final)
        m = self._marginal_prob(probs, self.target_bits)
        return -np.log(m + 1e-12)

    def _marginal_prob(self, probs: np.ndarray, bits: Tuple[int, ...]) -> float:
        total = 0.0
        for idx in range(2**self.n_qubits):
            match = True
            for q_idx, q in enumerate(self.readout_qubits):
                bit = (idx >> (self.n_qubits - 1 - q)) & 1
                if bit != bits[q_idx]:
                    match = False
                    break
            if match:
                total += probs[idx]
        return total

    def gradient_alpha_beta(self) -> GradientResult:
        """
        Exact gradient for alpha and beta using parameter-shift.

        For H = α X_a X_b + β Y_a Y_b + ...:
        The evolution is exp(-i H T).
        Parameter α appears as α * (X_a X_b) term.
        Since (X_a X_b)^2 = I, the generator has eigenvalues ±1.
        Parameter shift: α → α ± π/(2T) where T=π/2, so shift = 1.0
        """
        base_alpha = float(self.ham.alpha)
        base_beta = float(self.ham.beta)
        shift = 1.0  # π/(2T) with T=π/2

        # Alpha gradient
        ham_p = self.ham.copy()
        ham_p.alpha = base_alpha + shift
        loss_p = self._loss(ham_p)

        ham_m = self.ham.copy()
        ham_m.alpha = base_alpha - shift
        loss_m = self._loss(ham_m)

        grad_alpha = (loss_p - loss_m) / 2.0

        # Beta gradient
        ham_p = self.ham.copy()
        ham_p.beta = base_beta + shift
        loss_p = self._loss(ham_p)

        ham_m = self.ham.copy()
        ham_m.beta = base_beta - shift
        loss_m = self._loss(ham_m)

        grad_beta = (loss_p - loss_m) / 2.0

        return GradientResult(
            gradients=np.array([grad_alpha, grad_beta]),
            method='parameter_shift',
            evaluations=4,
            metadata={'shift': shift, 'base_alpha': base_alpha, 'base_beta': base_beta}
        )

    def gradient_hamiltonian_params(self, param_names: List[str]) -> GradientResult:
        """
        Parameter-shift gradients for all Hamiltonian parameters.

        For single-qubit terms h_i Z_i and h_i X_i, the generators
        are Z and X (eigenvalues ±1), so shift = π/(2T) = 1.0.
        """
        grads = []
        evaluations = 0
        shift = 1.0

        for param_name in param_names:
            if param_name == 'alpha':
                # Already computed
                res = self.gradient_alpha_beta()
                grads.append(res.gradients[0])
                evaluations += res.evaluations // 2
            elif param_name == 'beta':
                res = self.gradient_alpha_beta()
                grads.append(res.gradients[1])
                evaluations += res.evaluations // 2
            elif param_name.startswith('h_z'):
                i = int(param_name.split('_')[-1])
                old = float(self.ham.h_z[i])
                # Positive shift
                self.ham.h_z[i] = old + shift
                loss_p = self._loss(self.ham)
                # Negative shift
                self.ham.h_z[i] = old - shift
                loss_m = self._loss(self.ham)
                self.ham.h_z[i] = old
                grads.append((loss_p - loss_m) / 2.0)
                evaluations += 2
            elif param_name.startswith('h_x'):
                i = int(param_name.split('_')[-1])
                old = float(self.ham.h_x[i])
                self.ham.h_x[i] = old + shift
                loss_p = self._loss(self.ham)
                self.ham.h_x[i] = old - shift
                loss_m = self._loss(self.ham)
                self.ham.h_x[i] = old
                grads.append((loss_p - loss_m) / 2.0)
                evaluations += 2

        return GradientResult(
            gradients=np.array(grads),
            method='parameter_shift',
            evaluations=evaluations,
            metadata={'shift': shift, 'params': param_names}
        )


def parameter_shift_gradient(loss_fn: Callable[[float], float],
                              theta: float,
                              shift: float = np.pi/2) -> float:
    """
    Generic parameter-shift for any parameter θ.

    loss_fn: function taking parameter value, returning scalar loss
    theta: current parameter value
    shift: shift amount (π/2 for Pauli generators)
    """
    loss_p = loss_fn(theta + shift)
    loss_m = loss_fn(theta - shift)
    return (loss_p - loss_m) / 2.0


def parameter_shift_vectorized(loss_fn: Callable[[np.ndarray], float],
                                thetas: np.ndarray,
                                shift: float = np.pi/2) -> np.ndarray:
    """Vectorized parameter-shift for multiple parameters."""
    grads = np.zeros_like(thetas)
    for i in range(len(thetas)):
        theta_plus = thetas.copy()
        theta_minus = thetas.copy()
        theta_plus[i] += shift
        theta_minus[i] -= shift
        grads[i] = (loss_fn(theta_plus) - loss_fn(theta_minus)) / 2.0
    return grads


class HamiltonianParameterShift:
    """
    Complete parameter-shift gradient for all trainable Hamiltonian params.

    Handles:
    - alpha, beta (XX, YY interference)
    - h_z, h_x (single-qubit biases/fields)
    - J_ij (ZZ couplings) - note: these are generated by MLP, not direct params
    """

    def __init__(self, hamiltonian: RaslilaHamiltonian,
                 init_state: np.ndarray,
                 target_bits: Tuple[int, ...],
                 readout_qubits: Tuple[int, ...],
                 loss_type: str = 'nll'):
        self.ham = hamiltonian
        self.init_state = init_state
        self.target_bits = target_bits
        self.readout_qubits = readout_qubits
        self.loss_type = loss_type
        self.psg = ParameterShiftGradients(hamiltonian, init_state,
                                            target_bits, readout_qubits)

    def _loss(self, ham: RaslilaHamiltonian) -> float:
        H = ham.construct_dense()
        final = evolve(H, self.init_state, T_FIXED)
        probs = state_probs(final)
        m = self._marginal_prob(probs, self.target_bits)
        if self.loss_type == 'nll':
            return -np.log(m + 1e-12)
        elif self.loss_type == 'mse':
            return (m - 1.0)**2
        else:
            raise ValueError(f"Unknown loss type: {self.loss_type}")

    def _marginal_prob(self, probs: np.ndarray, bits: Tuple[int, ...]) -> float:
        total = 0.0
        for idx in range(2**self.ham.n):
            match = True
            for q_idx, q in enumerate(self.readout_qubits):
                bit = (idx >> (self.ham.n - 1 - q)) & 1
                if bit != bits[q_idx]:
                    match = False
                    break
            if match:
                total += probs[idx]
        return total

    def all_gradients(self) -> Dict[str, float]:
        """Compute exact gradients for all Hamiltonian parameters."""
        grads = {}

        # Alpha, beta
        res = self.psg.gradient_alpha_beta()
        grads['alpha'] = res.gradients[0]
        grads['beta'] = res.gradients[1]

        # Single-qubit h_z
        for i in range(self.ham.n):
            old = float(self.ham.h_z[i])
            shift = 1.0
            self.ham.h_z[i] = old + shift
            loss_p = self._loss(self.ham)
            self.ham.h_z[i] = old - shift
            loss_m = self._loss(self.ham)
            self.ham.h_z[i] = old
            grads[f'h_z[{i}]'] = (loss_p - loss_m) / 2.0

        # Single-qubit h_x
        for i in range(self.ham.n):
            old = float(self.ham.h_x[i])
            shift = 1.0
            self.ham.h_x[i] = old + shift
            loss_p = self._loss(self.ham)
            self.ham.h_x[i] = old - shift
            loss_m = self._loss(self.ham)
            self.ham.h_x[i] = old
            grads[f'h_x[{i}]'] = (loss_p - loss_m) / 2.0

        return grads

    def gradient_for_mlp(self, edge: Tuple[int, int],
                         property_vector: np.ndarray) -> np.ndarray:
        """
        Gradient of loss w.r.t J_ij for a specific edge.

        Uses parameter-shift on the coupling strength J.
        """
        old_J = float(self.ham.J.get(edge, 0.0))
        shift = 1.0

        self.ham.J[edge] = old_J + shift
        loss_p = self._loss(self.ham)
        self.ham.J[edge] = old_J - shift
        loss_m = self._loss(self.ham)
        self.ham.J[edge] = old_J

        grad_J = (loss_p - loss_m) / 2.0
        return np.array([grad_J])  # scalar gradient for this J


def finite_difference_gradient(loss_fn: Callable[[float], float],
                                theta: float,
                                eps: float = 1e-4) -> float:
    """Central finite difference for comparison/validation."""
    return (loss_fn(theta + eps) - loss_fn(theta - eps)) / (2 * eps)


def validate_parameter_shift(hamiltonian: RaslilaHamiltonian,
                              init_state: np.ndarray,
                              target_bits: Tuple[int, ...],
                              readout_qubits: Tuple[int, ...],
                              eps: float = 1e-4) -> Dict:
    """
    Validate parameter-shift gradients against finite difference.

    Returns dict with relative errors for each parameter.
    """
    psg = ParameterShiftGradients(hamiltonian, init_state,
                                   target_bits, readout_qubits)

    # Get exact parameter-shift gradients
    exact_res = psg.gradient_alpha_beta()
    exact_grads = {'alpha': exact_res.gradients[0], 'beta': exact_res.gradients[1]}

    # Finite difference for comparison
    def loss_fn(ham):
        H = ham.construct_dense()
        final = evolve(H, init_state, T_FIXED)
        probs = state_probs(final)
        m = psg._marginal_prob(probs, target_bits)
        return -np.log(m + 1e-12)

    fd_grads = {}
    for param in ['alpha', 'beta']:
        old = getattr(hamiltonian, param)
        ham_p = hamiltonian.copy()
        ham_m = hamiltonian.copy()
        setattr(ham_p, param, old + eps)
        setattr(ham_m, param, old - eps)
        fd_grads[param] = (loss_fn(ham_p) - loss_fn(ham_m)) / (2 * eps)

    errors = {}
    for param in ['alpha', 'beta']:
        if abs(exact_grads[param]) > 1e-8:
            errors[param] = abs(exact_grads[param] - fd_grads[param]) / abs(exact_grads[param])
        else:
            errors[param] = abs(exact_grads[param] - fd_grads[param])

    return {
        'exact': exact_grads,
        'finite_diff': fd_grads,
        'relative_errors': errors,
        'max_error': max(errors.values())
    }